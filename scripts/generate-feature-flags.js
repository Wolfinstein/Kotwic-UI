// Reads feature-flag env vars (set in the Vercel dashboard under
// Project Settings -> Environment Variables) at build time and writes them
// into a TS module the app can import. Angular's browser bundle has no
// `process` global, so this is the only way to get an env var into app code.
//
// Changing a var in the Vercel dashboard takes effect on the *next deploy*
// (click "Redeploy") — it is not picked up by already-built static assets.
const fs = require('fs');
const path = require('path');

const ekspedycjaEnabled = process.env.EKSPEDYCJA_ENABLED !== 'false';

const outPath = path.join(__dirname, '..', 'src', 'app', 'config', 'feature-flags.generated.ts');
const content = `// AUTO-GENERATED by scripts/generate-feature-flags.js — do not edit by hand.
// Regenerated on every build/serve from env vars (see that script for details).
export const FEATURE_FLAGS = {
  ekspedycjaEnabled: ${ekspedycjaEnabled}
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`[feature-flags] ekspedycjaEnabled = ${ekspedycjaEnabled}`);
